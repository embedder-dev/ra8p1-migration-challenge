#!/usr/bin/env python3
"""Generate the RA8P1 register view from Embedder's preserved SVD JSON.

The cache has no CMSIS-SVD dim/dimIncrement data. Ranged names are therefore
kept as a scalar first-element view; only explicitly documented arrays below
are expanded. No stride is inferred from a register's size or its neighbour.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / '.embedder/svd-cache/R7KA8P1AD.json'
DEFAULT_OUTPUT = ROOT / 'baseline/ra/fsp/src/bsp/cmsis/Device/RENESAS/Include/R7KA8P1AD.h'


def ident(name):
    return re.sub(r'[^A-Za-z0-9_]', '_', name)


def member_name(name):
    # Preserve the first physical element, not a fictitious array extent.
    return re.sub(r'(\d+)-\d+', r'\1', ident(name.replace('-', '-')))


def scalar_name(name):
    return ident(re.sub(r'(\d+)-\d+', r'\1', name))


def view(register, name=None, groups=()):
    name = name or scalar_name(register['name'])
    size = register['size']
    if size not in (8, 16, 32, 64):
        raise ValueError(f"Unsupported register size {size}: {name}")
    access = {'read-only': '__IM', 'write-only': '__OM', 'read-write': '__IOM'}[register['access']]
    result = [f'        {access} uint{size}_t {name};']
    fields = sorted(register['fields'], key=lambda f: f['bitOffset'])
    if fields:
        if groups:
            result += ['        union', '        {']
        result += ['        struct', '        {']
        end = 0
        used = set()
        for field in fields:
            start, width = field['bitOffset'], field['bitWidth']
            if start < end or start + width > size:
                raise ValueError(f"Invalid field layout: {name}.{field['name']}")
            if start > end:
                result += [f'            uint{size}_t : {start - end};']
            fname = ident(field['name'])
            if fname in used:
                raise ValueError(f'Duplicate field: {name}.{fname}')
            used.add(fname)
            result += [f'            {access} uint{size}_t {fname} : {width};']
            end = start + width
        if end < size:
            result += [f'            uint{size}_t : {size - end};']
        if groups:
            if sum(width for _, width in groups) != size:
                raise ValueError(f'Invalid grouped field layout: {name}')
            result += ['        };', '        struct', '        {']
            result += [f'            {access} uint{size}_t {field} : {width};'
                       for field, width in groups]
            result += ['        };']
        result += [f'        }} {name}_b;']
    return result


def generate(source):
    raw = source.read_bytes()
    device = json.loads(raw)
    if device['name'] != 'R7KA8P1AD':
        raise ValueError('Not the approved RA8P1 SVD')
    # R01UH1064EJ0120 sections 9.2.2 and 9.2.3 override incomplete SVD 1.10.02.
    for peripheral in device['peripherals']:
        if peripheral['name'] in ('SYSC', 'SYSC_NS'):
            for reg in peripheral['registers']:
                if reg['name'] == 'SCKDIVCR2':
                    reg['size'] = 16
                    reg['fields'].append(dict(name='MRICK', bitOffset=12, bitWidth=4, access='read-write'))
                if reg['name'] == 'SCKDIVCR':
                    reg['fields'].append(dict(name='PCKE', bitOffset=20, bitWidth=4, access='read-write'))
        # R01UH1064EJ0120 section 2.9.1: core registers have a 4-byte stride.
        if peripheral['name'] in ('CPU_CTRL', 'CPU_CTRL_NS'):
            expanded = []
            for reg in peripheral['registers']:
                if reg['name'].startswith('CPU0-1'):
                    for core in (0, 1):
                        expanded.append(dict(reg, name=reg['name'].replace('CPU0-1', f'CPU{core}'),
                                             addressOffset=reg['addressOffset'] + 4 * core))
                else:
                    expanded.append(reg)
            peripheral['registers'] = expanded
    lines = ['/* SPDX-License-Identifier: BSD-3-Clause',
             ' * Generated by tools/generate_ra8p1_device.py; do not edit.',
             f" * Source: R7KA8P1AD JSON {device['version']}; SHA256 {hashlib.sha256(raw).hexdigest()}",
             ' * Ranged SVD names expose only their first element unless documented below.',
             ' */', '#ifndef R7KA8P1AD_H', '#define R7KA8P1AD_H',
             '#include <stdint.h>', '#define __NVIC_PRIO_BITS 4U',
             '#define __Vendor_SysTickConfig 0U', '#define __VTOR_PRESENT 1U',
             '#define __MPU_PRESENT 1U', '#define __FPU_PRESENT 1U',
             '#define __DSP_PRESENT 1U', '#define __SAUREGION_PRESENT 1U',
             '#if BSP_CFG_CPU_CORE == 1', '#define __CM33_REV 0x0004U',
             '#define __ICACHE_PRESENT 0U', '#define __DCACHE_PRESENT 0U',
             '#include "core_cm33.h"', '#else', '#define __CM85_REV 0x0101U',
             '#define __FPU_DP 1U', '#define __ICACHE_PRESENT 1U',
             '#define __DCACHE_PRESENT 1U', '#define __PMU_PRESENT 1U',
             '#define __PMU_NUM_EVENTCNT 8U', '#include "core_cm85.h"', '#endif',
             '#include "system.h"']
    # HWM 21.2.1-4: one 0x20-byte port layout. Event registers are implemented
    # only on ports 1-4; the common FSP type includes that view for its event API.
    port0 = next(p for p in device['peripherals'] if p['name'] == 'PORT0')
    port1 = next(p for p in device['peripherals'] if p['name'] == 'PORT1')
    port_regs = port0['registers'] + [r for r in port1['registers']
                                     if r['name'] in ('PCNTR4', 'EOSR', 'EORR')]
    port_groups = {'PCNTR1': (('PDR', 16), ('PODR', 16)),
                   'PCNTR2': (('PIDR', 16), ('EIDR', 16)),
                   'PCNTR3': (('POSR', 16), ('PORR', 16)),
                   'PCNTR4': (('EOSR', 16), ('EORR', 16))}
    types = {}
    periph_types = {}
    for peripheral in device['peripherals']:
        is_port = re.fullmatch(r'PORT[0-9A-D](?:_NS)?', peripheral['name']) is not None
        regs = port_regs if is_port else peripheral.get('registers', [])
        key = json.dumps(regs, sort_keys=True)
        if key in types:
            periph_types[peripheral['name']] = types[key]
            if is_port:
                lines += [f'typedef {types[key]} R_{peripheral["name"]}_Type;']
                for reg in peripheral['registers']:
                    for field in reg['fields']:
                        base = f'R_{peripheral["name"]}_{scalar_name(reg["name"])}_{ident(field["name"])}'
                        mask = ((1 << field['bitWidth']) - 1) << field['bitOffset']
                        lines += [f'#define {base}_Pos ({field["bitOffset"]}U)',
                                  f'#define {base}_Msk (0x{mask:X}UL)']
            continue
        pname = ident(peripheral['name'])
        typename = f'R_{pname}_Type'
        types[key] = typename
        periph_types[peripheral['name']] = typename
        lines += [f'/* {peripheral["description"]} */', 'typedef union', '{']
        used = set()
        for reg in regs:
            name = scalar_name(reg['name'])
            # Some cache entries repeat the same first element with an alternate range.
            if name in used:
                name = ident(reg['name'])
            used.add(name)
            lines += ['    struct', '    {']
            if reg['addressOffset']:
                lines += [f'        uint8_t _reserved_{name}[0x{reg["addressOffset"]:X}];']
            lines += ['        union', '        {']
            lines += ['    ' + s for s in view(reg, name, port_groups.get(name, ()) if is_port else ())]
            lines += ['        };', '    };']
        if is_port:
            lines += ['    uint8_t _port_stride[0x20];']
        # R01UH1064EJ0120 14.2.17: local ICU bank, 96 slots at four-byte pitch.
        if peripheral['name'] in ('ICU', 'ICU_NS'):
            lines += ['    struct { uint8_t _ielsr_padding[0x300]; __IOM uint32_t IELSR[96]; };',
                      '    struct { uint8_t _ielsr_bits_padding[0x300]; struct {',
                      '        __IOM uint32_t IELS : 10; uint32_t : 6;',
                      '        __IOM uint32_t IR : 1; uint32_t : 7;',
                      '        __IOM uint32_t DTCE : 1; uint32_t : 7;',
                      '    } IELSR_b[96]; };']
        # HWM PFS: four-byte pin / 0x40-byte port pitch. Use SVD bitfields.
        if peripheral['name'] in ('PFS', 'PFS_NS'):
            pin = next(r for r in regs if r['name'] == 'P000-9PFS')
            lines += ['    struct { struct { union {']
            lines += ['    ' + s for s in view(pin, 'PmnPFS')]
            lines += ['    }; } PIN[16]; } PORT[14];']
            protection_offset = 0x514 if peripheral['name'] == 'PFS' else 0x50C
            lines += [f'    struct {{ uint8_t _pwpr_padding[0x{protection_offset:X}]; __IOM uint8_t PWPR; }};',
                      f'    struct {{ uint8_t _pwprs_padding[0x{protection_offset:X}]; __IOM uint8_t PWPRS; }};']
        if peripheral['name'] in ('SYSC', 'SYSC_NS'):
            lines += ['    struct { uint8_t _prcr_padding[0x3FA]; __IOM uint16_t PRCR; };']
        lines += [f'}} {typename};']
        for reg in regs:
            rn = scalar_name(reg['name'])
            for field in reg['fields']:
                base = f'R_{pname}_{rn}_{ident(field["name"])}'
                lines += [f'#define {base}_Pos ({field["bitOffset"]}U)',
                          f'#define {base}_Msk (0x{((1 << field["bitWidth"]) - 1) << field["bitOffset"]:X}UL)']
    lines += ['/* Physical secure and non-secure views; selected view follows the existing BSP contract. */']
    for peripheral in device['peripherals']:
        name = ident(peripheral['name'])
        lines += [f'#define R_{name}_BASE (0x{peripheral["baseAddress"]:08X}UL)',
                  f'#define R_{name} (({periph_types[peripheral["name"]]} *) R_{name}_BASE)']
    aliases = {'SYSTEM': 'SYSC', 'PMISC': 'PFS', 'WDT': 'WDT0', 'GPT0': 'GPT320',
               'DAC_B': 'DAC0_B', 'TSN_CTRL': 'TSN', 'TSN_CAL': 'TSD'}
    lines += ['typedef R_SYSC_Type R_SYSTEM_Type;', 'typedef R_WDT0_Type R_WDT_Type;',
              'typedef R_GPT320_Type R_GPT0_Type;', 'typedef R_DAC0_B_Type R_DAC_B_Type;']
    for dst, src in aliases.items():
        if dst.endswith('_Type'):
            continue
        lines += [f'#define R_{dst} R_{src}', f'#define R_{dst}_BASE R_{src}_BASE']
    # Retain baseline spellings for common register bit constants, not address aliases.
    for p in device['peripherals']:
        if p['name'] == 'SYSC':
            for r in p['registers']:
                for f in r['fields']:
                    b = f'{scalar_name(r["name"])}_{ident(f["name"])}'
                    lines += [f'#define R_SYSTEM_{b}_Pos R_SYSC_{b}_Pos',
                              f'#define R_SYSTEM_{b}_Msk R_SYSC_{b}_Msk']
    # ADC_B temperature-sensor setup uses PRCR at the secure-view address.
    lines += ['#define R_SYSTEM_PRCR_PRC5_Pos R_SYSC_PRCR_S_PRC5_Pos',
              '#define R_SYSTEM_PRCR_PRC5_Msk R_SYSC_PRCR_S_PRC5_Msk']
    # FSP 5.9 ADC_B keeps its original RA6T2 field spellings. Alias only
    # existing RA8P1 fields; absent PGA and extended channels remain absent.
    adc = next(p for p in device['peripherals'] if p['name'] == 'ADC_B')
    for register in adc['registers']:
        for field in register['fields']:
            suffix = f'{scalar_name(register["name"])}_{ident(field["name"])}'
            for kind in ('Pos', 'Msk'):
                lines.append(f'#define R_ADC_B0_{suffix}_{kind} R_ADC_B_{suffix}_{kind}')
    lines += ['#define R_ADC_B0_ADDR_ERR_Pos R_ADC_B_ADDR0_ERR_Pos',
              '#define R_ADC_B0_ADDR_ERR_Msk R_ADC_B_ADDR0_ERR_Msk']
    # The old headers group the per-channel clear bits into one field. Build
    # those masks from the SVD rather than extending into reserved bits.
    for register_name, field_name in (('ADFIFODCR', 'FIFODCn'), ('ADOVFCHSCR0', 'OVFCHCn')):
        register = next(r for r in adc['registers'] if r['name'] == register_name)
        mask = 0
        for field in register['fields']:
            mask |= ((1 << field['bitWidth']) - 1) << field['bitOffset']
        position = min(f['bitOffset'] for f in register['fields'])
        lines += [f'#define R_ADC_B0_{register_name}_{field_name}_Pos ({position}U)',
                  f'#define R_ADC_B0_{register_name}_{field_name}_Msk (0x{mask:X}UL)']
    # The SVD range describes identical fields, not an inferred register stride.
    # FSP's generated ADC configuration references every limiter/filter field.
    for register_name, count in (('ADLIMTR', 8), ('ADDFSR', 2)):
        register = next(r for r in adc['registers'] if r['name'] == f'{register_name}0-{count - 1}')
        for index in range(1, count):
            for field in register['fields']:
                for kind in ('Pos', 'Msk'):
                    suffix = f'{ident(field["name"])}_{kind}'
                    lines.append(f'#define R_ADC_B0_{register_name}{index}_{suffix} '
                                 f'R_ADC_B_{register_name}0_{suffix}')
    # Option memory is absent from SVD 1.10.02. R01UH1064EJ0130 7.2.1,
    # 7.2.6 and 7.2.7 define these read-only views; no programming interface.
    for name, address in (('OFS0', 0x02C9F040), ('OFS3', 0x12C9F4C4),
                          ('OFS3_SEC', 0x02C9F0C4), ('OFS3_SEL', 0x02C9F124)):
        lines += [f'#define R_{name}_ADDRESS (0x{address:08X}UL)',
                  f'#define R_{name} ((volatile const uint32_t *) R_{name}_ADDRESS)']
    lines += ['#endif', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=DEFAULT_SOURCE)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate(args.source)
    if args.check:
        if args.output.read_text() != content:
            parser.exit(1, 'RA8P1 header is not reproducible from the approved SVD\n')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content)


if __name__ == '__main__':
    main()
